def run_simulation_demonstration(
    output_model_path: str = "demo_qnn_model.json",
    n_samples: int = 80,
    maxiter: int = 35,
) -> Dict[str, Any]:
    """
    Executes a complete self-contained simulation demonstration:
    1. Logs scientific disclaimers.
    2. Generates synthetic genetic benchmark data.
    3. Builds and inspects the 4-qubit parameterized quantum circuit.
    4. Trains the hybrid quantum classifier via Qiskit StatevectorEstimator.
    5. Evaluates classification performance (loss, accuracy).
    6. Verifies model serialization and persistence.

    Does NOT require IBM Quantum hardware or internet access.
    """
    print("\n" + "=" * 76)
    print(" HELIX GUARD: QUANTUM NEURAL NETWORK (QNN) ENGINE DEMONSTRATION")
    print("=" * 76)
    print("[NOTE] Experimental research prototype for computational genetics.")
    print("[NOTE] No quantum advantage is claimed. Validated on synthetic demo data.")
    print("[NOTE] Does not generate clinical edits or recommend embryo procedures.")
    print("=" * 76 + "\n")

    # Step 1: Generate labeled synthetic data
    X, y, feature_names = generate_synthetic_genetic_data(
        n_samples=n_samples, seed=42
    )
    n_train = int(len(X) * 0.75)
    X_train, X_test = X[:n_train], X[n_train:]
    y_train, y_test = y[:n_train], y[n_train:]

    print(f"[*] Generated synthetic dataset: {len(X)} samples across 4 features:")
    for fn in feature_names:
        print(f"    - {fn}")
    print(f"[*] Split: {len(X_train)} train, {len(X_test)} test samples.\n")

    # Step 2: Initialize QNN
    print("[*] Initializing 4-qubit Hybrid Quantum Classifier...")
    clf = HybridQuantumClassifier(
        num_qubits=4,
        feature_map_type="zz",
        ansatz_type="real_amplitudes",
        feature_reps=1,
        ansatz_reps=2,
        entanglement="linear",
        optimizer_name="COBYLA",
        maxiter=maxiter,
        random_state=42,
    )

    summary = clf.summary()
    print(f"[*] Circuit Summary:")
    print(f"    - Qubits: {summary['num_qubits']}")
    print(f"    - Feature Map Parameters: {summary['feature_map_parameters']}")
    print(f"    - Trainable Ansatz Parameters: {summary['ansatz_trainable_parameters']}")
    print(f"    - Circuit Depth: {summary['circuit_depth']}")
    print(f"    - Total Operations: {summary['num_circuit_operations']}\n")

    # Step 3: Train model
    print(f"[*] Commencing simulation-based training via StatevectorEstimator...")
    clf.fit(X_train, y_train, verbose=True)

    # Step 4: Evaluate
    train_acc = clf.score(X_train, y_train)
    test_acc = clf.score(X_test, y_test)
    sample_probs = clf.predict_proba(X_test[:5])

    print(f"\n[*] Training Completed:")
    print(f"    - Final Training Loss: {clf.training_history_[-1]:.4f}")
    print(f"    - Synthetic Train Accuracy: {train_acc * 100:.2f}%")
    print(f"    - Synthetic Test Accuracy:  {test_acc * 100:.2f}%")
    print("\n[*] Sample Test Predictions (Synthetic Probabilities):")
    for i in range(min(5, len(sample_probs))):
        pred_label = "Synthetic Class 1 (Pathogenic-like)" if sample_probs[i, 1] >= 0.5 else "Synthetic Class 0 (Benign-like)"
        print(
            f"    Sample #{i+1}: True={y_test[i]} | "
            f"P(Class 0)={sample_probs[i, 0]:.3f}, P(Class 1)={sample_probs[i, 1]:.3f} "
            f"--> [{pred_label}]"
        )

    # Step 5: Save and reload test
    print(f"\n[*] Serializing trained model to {output_model_path}...")
    clf.save(output_model_path)
    reloaded = HybridQuantumClassifier.load(output_model_path)
    reloaded_acc = reloaded.score(X_test, y_test)
    assert np.isclose(test_acc, reloaded_acc), "Reloaded accuracy mismatch!"
    print(f"[*] Reloaded model verified. Integrity check PASSED.\n")
    print("=" * 76)
    print(" DEMONSTRATION COMPLETE: QNN Engine ready for modular ClinVar expansion.")
    print("=" * 76 + "\n")

    return {
        "train_accuracy": train_acc,
        "test_accuracy": test_acc,
        "circuit_summary": summary,
        "model_path": output_model_path,
    }


if __name__ == "__main__":
    run_simulation_demonstration()
