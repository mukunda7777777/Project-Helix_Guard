class CompactFeatureAdapter:
    """
    Transforms raw genomic sequence windows or ClinVar variant records into
    a compact numerical feature vector (default: 4 dimensions) suitable for
    qubit state encoding.

    DNA sequences are NOT encoded directly into the quantum circuit; instead,
    compact statistical, biochemical, and population metrics are extracted.
    """

    FEATURE_NAMES = [
        "allele_frequency",       # Population frequency (rare -> high pathogenicity risk)
        "conservation_score",     # In-silico conservation / functional tolerance metric
        "local_gc_content",       # Flanking GC proportion [0, 1]
        "molecular_impact_score", # Biochemical substitution / radical change score [0, 1]
    ]

    @staticmethod
    def extract_from_sequence_window(
        sequence: str,
        variant_position: Optional[int] = None,
        alt_base: Optional[str] = None,
    ) -> np.ndarray:
        """
        Derives a 4-dimensional compact feature vector from a DNA sequence window.

        Features extracted:
        0: Estimated frequency index (approximated based on local motif rarity)
        1: Local sequence conservation / complexity proxy (entropy)
        2: GC content ratio within window [0.0, 1.0]
        3: Substitution impact score (transition=0.25, transversion=0.75, indel/radical=1.0)
        """
        if not isinstance(sequence, str) or len(sequence) == 0:
            raise ValueError("Sequence must be a non-empty string.")

        clean_seq = sequence.upper().strip()
        seq_len = len(clean_seq)

        # 1. Local GC content
        gc_count = clean_seq.count("G") + clean_seq.count("C")
        gc_content = float(gc_count) / float(seq_len)

        # 2. Sequence Shannon entropy proxy (complexity / conservation baseline)
        base_counts = [clean_seq.count(b) for b in "ACGT"]
        probs = [c / seq_len for c in base_counts if c > 0]
        entropy = -sum(p * np.log2(p) for p in probs) / 2.0  # normalized to [0, 1]

        # 3. CpG dinucleotide density (indicator of regulatory fragility / methylation targets)
        cpg_count = clean_seq.count("CG")
        cpg_density = min(1.0, float(cpg_count * 10) / float(max(1, seq_len)))

        # 4. Mutation impact score
        impact_score = 0.5  # neutral default
        if variant_position is not None and 0 <= variant_position < seq_len and alt_base:
            ref_base = clean_seq[variant_position]
            alt = alt_base.upper()
            if ref_base == alt:
                impact_score = 0.0
            else:
                purines = {"A", "G"}
                pyrimidines = {"C", "T"}
                is_transition = (ref_base in purines and alt in purines) or (
                    ref_base in pyrimidines and alt in pyrimidines
                )
                impact_score = 0.3 if is_transition else 0.8

        feature_vec = np.array(
            [cpg_density, entropy, gc_content, impact_score], dtype=np.float64
        )
        return feature_vec

    @staticmethod
    def extract_from_clinvar_record(record: Dict[str, Any]) -> np.ndarray:
        """
        Extracts a compact numerical feature vector from a ClinVar record dictionary.

        Handles missing fields gracefully using biological median defaults.
        """
        if not isinstance(record, dict):
            raise TypeError("ClinVar record must be a dictionary.")

        # 1. Allele frequency (AF_ESP, AF_EXAC, AF_TGP)
        af_candidates = []
        for key in ["AF_EXAC", "AF_TGP", "AF_ESP"]:
            val = record.get(key)
            if val is not None:
                try:
                    v_float = float(val)
                    if not np.isnan(v_float):
                        af_candidates.append(v_float)
                except (ValueError, TypeError):
                    pass
        raw_af = min(af_candidates) if af_candidates else 0.0001
        # Convert AF into rare-variant risk scale: log-transformed rarity in [0, 1]
        allele_freq_score = float(np.clip(-np.log10(max(raw_af, 1e-6)) / 6.0, 0.0, 1.0))

        # 2. Conservation / In-silico score (e.g. CADD_PHRED or LoFtool)
        cadd_raw = record.get("CADD_PHRED", 15.0)
        try:
            cadd_val = float(cadd_raw)
            if np.isnan(cadd_val):
                cadd_val = 15.0
        except (ValueError, TypeError):
            cadd_val = 15.0
        cadd_norm = float(np.clip(cadd_val / 40.0, 0.0, 1.0))

        # 3. Local GC or consequence impact
        consequence = str(record.get("Consequence", "")).lower()
        if any(term in consequence for term in ["stop_gained", "frameshift", "splice"]):
            consequence_severity = 0.95
        elif "missense" in consequence:
            consequence_severity = 0.60
        elif "synonymous" in consequence:
            consequence_severity = 0.10
        else:
            consequence_severity = 0.40

        # 4. BLOSUM62 / Molecular impact
        blosum = record.get("BLOSUM62", 0.0)
        try:
            b_val = float(blosum)
            if np.isnan(b_val):
                b_val = 0.0
        except (ValueError, TypeError):
            b_val = 0.0
        # BLOSUM range roughly -4 to +4: map to [0, 1] inverted (negative BLOSUM = radical change)
        molecular_impact = float(np.clip((4.0 - b_val) / 8.0, 0.0, 1.0))

        return np.array(
            [allele_freq_score, cadd_norm, consequence_severity, molecular_impact],
            dtype=np.float64,
        )


