@dataclass
class CircuitArchitectureConfig:
    num_qubits: int = 4
    feature_map_type: str = "zz"   # "zz", "angle", "z"
    ansatz_type: str = "real_amplitudes" # "real_amplitudes", "two_local"
    feature_reps: int = 1
    ansatz_reps: int = 2
    entanglement: str = "linear"    # "linear", "full", "circular"


class QuantumCircuitBuilder:
    """
    Constructs parameterized quantum circuits combining feature-encoding
    layers with variational ansatz layers using native Qiskit 2.x APIs.
    """

    def __init__(self, config: Optional[CircuitArchitectureConfig] = None):
        self.config = config or CircuitArchitectureConfig()
        if self.config.num_qubits < 1:
            raise ValueError("Number of qubits must be at least 1.")
        if self.config.num_qubits > 16:
            raise ValueError(
                f"num_qubits={self.config.num_qubits} is too large for fast "
                "statevector simulation. Please use <= 16 qubits."
            )

    def build_feature_map(self) -> QuantumCircuit:
        """Constructs the feature encoding circuit."""
        n_q = self.config.num_qubits
        f_type = self.config.feature_map_type.lower()
        reps = self.config.feature_reps

        if f_type == "zz":
            return zz_feature_map(
                feature_dimension=n_q,
                reps=reps,
                entanglement=self.config.entanglement,
            )
        elif f_type == "angle":
            # Direct Ry angle encoding
            qc = QuantumCircuit(n_q, name="AngleEncoding")
            x = ParameterVector("x", n_q)
            for r in range(reps):
                for i in range(n_q):
                    qc.ry(x[i], i)
            return qc
        elif f_type == "z":
            # Z feature map (H followed by Rz)
            qc = QuantumCircuit(n_q, name="ZFeatureMap")
            x = ParameterVector("x", n_q)
            for r in range(reps):
                for i in range(n_q):
                    qc.h(i)
                    qc.rz(x[i], i)
            return qc
        else:
            raise ValueError(
                f"Unsupported feature_map_type: {f_type}. Choose 'zz', 'angle', or 'z'."
            )

    def build_ansatz(self) -> QuantumCircuit:
        """Constructs the parameterized variational ansatz circuit."""
        n_q = self.config.num_qubits
        a_type = self.config.ansatz_type.lower()
        reps = self.config.ansatz_reps

        if a_type == "real_amplitudes":
            return real_amplitudes(
                num_qubits=n_q,
                reps=reps,
                entanglement=self.config.entanglement,
            )
        elif a_type == "two_local":
            qc = QuantumCircuit(n_q, name="TwoLocal")
            theta = ParameterVector("theta", n_q * (reps + 1) * 2)
            param_idx = 0
            for r in range(reps):
                for i in range(n_q):
                    qc.ry(theta[param_idx], i)
                    param_idx += 1
                    qc.rz(theta[param_idx], i)
                    param_idx += 1
                for i in range(n_q - 1):
                    qc.cx(i, i + 1)
            # Final rotation layer
            for i in range(n_q):
                qc.ry(theta[param_idx], i)
                param_idx += 1
                qc.rz(theta[param_idx], i)
                param_idx += 1
            return qc
        else:
            raise ValueError(
                f"Unsupported ansatz_type: {a_type}. Choose 'real_amplitudes' or 'two_local'."
            )

    def build_composite_circuit(self) -> Tuple[QuantumCircuit, List[Parameter], List[Parameter]]:
        """
        Combines feature map and variational ansatz into a single executable circuit.

        Returns:
            composite_circuit: Complete QuantumCircuit
            feature_params: Parameters corresponding to inputs
            weight_params: Parameters corresponding to trainable weights
        """
        fm = self.build_feature_map()
        ansatz = self.build_ansatz()
        composite = fm.compose(ansatz)

        feature_params = list(fm.parameters)
        weight_params = list(ansatz.parameters)

        return composite, feature_params, weight_params

    def get_default_observable(self) -> SparsePauliOp:
        """
        Constructs the default measurement observable:
        Total average Pauli-Z expectation across all qubits: O = (1/N) * sum_i Z_i
        """
        n_q = self.config.num_qubits
        pauli_terms = []
        coeff = 1.0 / float(n_q)
        for i in range(n_q):
            label = ["I"] * n_q
            label[i] = "Z"
            pauli_terms.append(("".join(label), coeff))
        return SparsePauliOp.from_list(pauli_terms)


