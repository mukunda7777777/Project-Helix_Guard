class QuantumFeatureNormalizer:
    """
    Min-Max feature normalizer that scales numerical inputs into a target
    angular range (default: [0, pi]) suitable for quantum state rotation gates.

    Preserves fitted parameters (feature minima and ranges) to ensure
    consistent inference and invertible transformations.
    """

    def __init__(
        self,
        target_range: Tuple[float, float] = (0.0, np.pi),
        clip: bool = True,
    ):
        if target_range[0] >= target_range[1]:
            raise ValueError(
                f"target_range lower bound ({target_range[0]}) must be strictly "
                f"less than upper bound ({target_range[1]})."
            )
        self.target_range = (float(target_range[0]), float(target_range[1]))
        self.clip = clip
        self.data_min_: Optional[np.ndarray] = None
        self.data_max_: Optional[np.ndarray] = None
        self.data_range_: Optional[np.ndarray] = None
        self.n_features_in_: Optional[int] = None

    def fit(self, X: np.ndarray) -> "QuantumFeatureNormalizer":
        """Computes per-feature minimum and maximum from training data."""
        X_arr = self._validate_data(X)
        self.n_features_in_ = X_arr.shape[1]
        self.data_min_ = np.nanmin(X_arr, axis=0)
        self.data_max_ = np.nanmax(X_arr, axis=0)
        self.data_range_ = self.data_max_ - self.data_min_

        # Avoid zero division for constant columns
        self.data_range_[self.data_range_ == 0.0] = 1.0
        return self

    def transform(self, X: np.ndarray) -> np.ndarray:
        """Scales X to the target range using fitted statistics."""
        if self.data_min_ is None or self.data_range_ is None:
            raise RuntimeError("Normalizer has not been fitted yet. Call fit() first.")
        X_arr = self._validate_data(X)
        if X_arr.shape[1] != self.n_features_in_:
            raise ValueError(
                f"Feature dimension mismatch: expected {self.n_features_in_}, "
                f"got {X_arr.shape[1]}."
            )

        t_min, t_max = self.target_range
        scaled = (X_arr - self.data_min_) / self.data_range_
        scaled_target = scaled * (t_max - t_min) + t_min

        if self.clip:
            scaled_target = np.clip(scaled_target, t_min, t_max)

        return scaled_target

    def fit_transform(self, X: np.ndarray) -> np.ndarray:
        """Fits normalizer and transforms input in a single step."""
        return self.fit(X).transform(X)

    def inverse_transform(self, X_scaled: np.ndarray) -> np.ndarray:
        """Transforms scaled angular features back to original scale."""
        if self.data_min_ is None or self.data_range_ is None:
            raise RuntimeError("Normalizer has not been fitted yet.")
        X_arr = self._validate_data(X_scaled)
        t_min, t_max = self.target_range
        unit_scaled = (X_arr - t_min) / (t_max - t_min)
        return unit_scaled * self.data_range_ + self.data_min_

    def _validate_data(self, X: Any) -> np.ndarray:
        try:
            arr = np.asarray(X, dtype=np.float64)
        except Exception as e:
            raise ValueError(f"Input data must be numeric array-like: {e}")

        if arr.ndim == 1:
            arr = arr.reshape(1, -1)
        elif arr.ndim != 2:
            raise ValueError(f"Input must be 2D array (samples, features), got ndim={arr.ndim}")

        if arr.size == 0:
            raise ValueError("Input array must not be empty.")

        if np.any(np.isnan(arr)) or np.any(np.isinf(arr)):
            raise ValueError("Input array contains NaN or infinite values.")

        return arr

    def to_dict(self) -> Dict[str, Any]:
        """Serializes normalizer state to a plain dictionary."""
        return {
            "target_range": list(self.target_range),
            "clip": self.clip,
            "n_features_in": self.n_features_in_,
            "data_min": self.data_min_.tolist() if self.data_min_ is not None else None,
            "data_max": self.data_max_.tolist() if self.data_max_ is not None else None,
            "data_range": self.data_range_.tolist() if self.data_range_ is not None else None,
        }

    @classmethod
    def from_dict(cls, state: Dict[str, Any]) -> "QuantumFeatureNormalizer":
        """Restores normalizer state from a dictionary."""
        norm = cls(
            target_range=tuple(state["target_range"]),
            clip=state.get("clip", True),
        )
        norm.n_features_in_ = state.get("n_features_in")
        if state.get("data_min") is not None:
            norm.data_min_ = np.array(state["data_min"], dtype=np.float64)
            norm.data_max_ = np.array(state["data_max"], dtype=np.float64)
            norm.data_range_ = np.array(state["data_range"], dtype=np.float64)
        return norm


