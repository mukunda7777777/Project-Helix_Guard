class HybridQuantumClassifier:
    """
    Hybrid Quantum-Classical Neural Network Classifier for genetic-variant risk research.

    Features:
    - Input normalization to angular bounds [0, pi].
    - Quantum encoding via parameterized feature map (ZZFeatureMap / AngleEncoding).
    - Variational parameterized ansatz (RealAmplitudes / TwoLocal).
    - Fast exact expectation-value evaluation via Qiskit StatevectorEstimator.
    - Vectorized batched execution across samples.
    - Training via gradient-free (COBYLA/SLSQP) or exact Parameter-Shift gradient optimizers.
    - Full serialization (JSON / dictionary) and prediction interfaces (predict / predict_proba).
    - Modular architecture designed for future ClinVar benchmark ingestion.
    """

    def __init__(
        self,
        num_qubits: int = 4,
        feature_map_type: str = "zz",
        ansatz_type: str = "real_amplitudes",
        feature_reps: int = 1,
        ansatz_reps: int = 2,
        entanglement: str = "linear",
        optimizer_name: str = "COBYLA",
        maxiter: int = 50,
        random_state: Optional[int] = 42,
    ):
        self.config = CircuitArchitectureConfig(
            num_qubits=num_qubits,
            feature_map_type=feature_map_type,
            ansatz_type=ansatz_type,
            feature_reps=feature_reps,
            ansatz_reps=ansatz_reps,
            entanglement=entanglement,
        )
        self.optimizer_name = optimizer_name.upper()
        self.maxiter = maxiter
        self.random_state = random_state

        # Circuit & normalizer components
        self.normalizer = QuantumFeatureNormalizer(target_range=(0.0, np.pi))
        self.builder = QuantumCircuitBuilder(self.config)
        self.circuit, self.feature_params, self.weight_params = (
            self.builder.build_composite_circuit()
        )
        self.observable = self.builder.get_default_observable()
        self.estimator = StatevectorEstimator()

        # Map parameter binding indices
        self.circuit_params = list(self.circuit.parameters)
        param_to_idx = {p: i for i, p in enumerate(self.circuit_params)}
        self.input_param_indices = [param_to_idx[p] for p in self.feature_params]
        self.weight_param_indices = [param_to_idx[p] for p in self.weight_params]

        # Trainable state
        self.num_weights = len(self.weight_params)
        self.weights_: Optional[np.ndarray] = None
        self.is_fitted_: bool = False
        self.training_history_: List[float] = []

        # Initialize weights with fixed seed if provided
        rng = np.random.RandomState(self.random_state)
        self.initial_point = rng.normal(0.0, 0.1, size=self.num_weights)

    def _evaluate_expectation_batch(
        self,
        X_scaled: np.ndarray,
        weights: np.ndarray,
    ) -> np.ndarray:
        """
        Evaluates the expectation value <O> for a batch of inputs in a single vectorized pass.

        Returns array of shape (batch_size,) with expectation values in [-1, 1].
        """
        batch_size = len(X_scaled)
        if batch_size == 0:
            return np.empty((0,), dtype=np.float64)

        num_total_params = len(self.circuit_params)
        ordered_values = np.empty((batch_size, num_total_params), dtype=np.float64)
        ordered_values[:, self.input_param_indices] = X_scaled
        ordered_values[:, self.weight_param_indices] = weights

        pub = (self.circuit, self.observable, ordered_values)
        job = self.estimator.run([pub])
        evs = job.result()[0].data.evs
        return np.asarray(evs, dtype=np.float64)

    def _loss(
        self,
        weights: np.ndarray,
        X_scaled: np.ndarray,
        y: np.ndarray,
        loss_type: str = "bce",
        sample_weights: Optional[np.ndarray] = None,
    ) -> float:
        """Computes loss over current weights."""
        evs = self._evaluate_expectation_batch(X_scaled, weights)
        # Rescale expectation value <O> in [-1, 1] to probability in [0, 1]
        probs = np.clip((evs + 1.0) / 2.0, 1e-7, 1.0 - 1e-7)

        if loss_type == "bce":
            bce = -(y * np.log(probs) + (1.0 - y) * np.log(1.0 - probs))
            if sample_weights is not None:
                loss = float(np.mean(sample_weights * bce))
            else:
                loss = float(np.mean(bce))
        else:
            se = (probs - y) ** 2
            if sample_weights is not None:
                loss = float(np.mean(sample_weights * se))
            else:
                loss = float(np.mean(se))
        return loss

    def fit(
        self,
        X: np.ndarray,
        y: np.ndarray,
        loss_type: str = "bce",
        class_weight: Optional[Union[str, Dict[int, float]]] = None,
        callback: Optional[Callable[[int, float], None]] = None,
        verbose: bool = False,
    ) -> "HybridQuantumClassifier":
        """
        Trains the parameterized quantum circuit on input data.

        Args:
            X: Input features of shape (n_samples, n_features)
            y: Binary target labels (0 or 1) of shape (n_samples,)
            loss_type: "bce" (Binary Cross Entropy) or "mse" (Mean Squared Error)
            class_weight: Optional "balanced" or dict mapping class {0: w0, 1: w1}
            callback: Optional callable(iteration, current_loss)
            verbose: If True, logs training loss progress

        Returns:
            self
        """
        # Validate data
        X_arr = np.asarray(X, dtype=np.float64)
        if X_arr.ndim == 1:
            X_arr = X_arr.reshape(1, -1)
        if X_arr.shape[1] != len(self.feature_params):
            raise ValueError(
                f"Feature dimension mismatch: quantum circuit expects {len(self.feature_params)} features, "
                f"got {X_arr.shape[1]}."
            )

        X_norm = self.normalizer.fit_transform(X)
        y_arr = np.asarray(y, dtype=np.float64).ravel()

        if len(X_norm) != len(y_arr):
            raise ValueError(
                f"Sample count mismatch: X has {len(X_norm)} samples, y has {len(y_arr)}."
            )
        if len(np.unique(y_arr)) > 2:
            raise ValueError("Target y must contain binary labels (e.g. 0 and 1).")
        if not np.all(np.isin(y_arr, [0.0, 1.0])):
            # Automatically clip continuous targets or binarize if necessary
            y_arr = np.where(y_arr >= 0.5, 1.0, 0.0)

        # Compute sample weights if class_weight is provided
        sample_weights = None
        if class_weight == "balanced":
            n_total = len(y_arr)
            classes, counts = np.unique(y_arr, return_counts=True)
            n_classes = len(classes)
            sample_weights = np.ones(n_total, dtype=np.float64)
            for c, cnt in zip(classes, counts):
                w_c = n_total / (n_classes * cnt) if cnt > 0 else 1.0
                sample_weights[y_arr == c] = w_c
        elif isinstance(class_weight, dict):
            sample_weights = np.ones(len(y_arr), dtype=np.float64)
            for c, w in class_weight.items():
                sample_weights[y_arr == c] = float(w)

        self.training_history_ = []
        iteration_counter = [0]

        def objective(w: np.ndarray) -> float:
            loss = self._loss(w, X_norm, y_arr, loss_type=loss_type, sample_weights=sample_weights)
            iteration_counter[0] += 1
            self.training_history_.append(loss)
            if verbose and iteration_counter[0] % 10 == 0:
                logger.info(
                    f"Iteration {iteration_counter[0]}/{self.maxiter} - Loss: {loss:.5f}"
                )
            if callback is not None:
                callback(iteration_counter[0], loss)
            return loss

        # Run optimization
        logger.info(
            f"Beginning QNN training with optimizer={self.optimizer_name}, "
            f"qubits={self.config.num_qubits}, weights={self.num_weights}."
        )

        res = minimize(
            objective,
            x0=self.initial_point,
            method=self.optimizer_name,
            options={"maxiter": self.maxiter},
        )

        self.weights_ = res.x
        self.is_fitted_ = True
        logger.info(
            f"Training finished. Final Loss: {res.fun:.5f} (Success: {res.success})."
        )
        return self

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        """
        Predicts continuous pathogenicity risk probabilities for input features.

        Args:
            X: Input feature array of shape (n_samples, n_features)

        Returns:
            probabilities: Array of shape (n_samples, 2), where column 0 is P(Benign)
                          and column 1 is P(Pathogenic / High Risk).
        """
        if not self.is_fitted_ or self.weights_ is None:
            raise RuntimeError("Model is not fitted yet. Call fit() before predicting.")

        X_scaled = self.normalizer.transform(X)
        evs = self._evaluate_expectation_batch(X_scaled, self.weights_)
        # Map expectation value [-1, 1] to continuous risk probability [0, 1]
        p_class1 = np.clip((evs + 1.0) / 2.0, 0.0, 1.0)
        p_class0 = 1.0 - p_class1

        return np.column_stack([p_class0, p_class1])

    def predict(self, X: np.ndarray, threshold: float = 0.5) -> np.ndarray:
        """
        Predicts discrete binary classification labels (0 or 1).

        Args:
            X: Input feature array of shape (n_samples, n_features)
            threshold: Probability threshold for class 1 (default: 0.5)

        Returns:
            labels: Integer array of shape (n_samples,) with values in {0, 1}
        """
        probs = self.predict_proba(X)[:, 1]
        return np.where(probs >= threshold, 1, 0)

    def score(self, X: np.ndarray, y: np.ndarray) -> float:
        """Computes classification accuracy score on given test data and labels."""
        preds = self.predict(X)
        y_true = np.asarray(y, dtype=int).ravel()
        return float(np.mean(preds == y_true))

    def save(self, filepath: str) -> str:
        """
        Saves trained model state, weights, architecture, and normalizer to a JSON file.
        """
        if not self.is_fitted_ or self.weights_ is None:
            raise RuntimeError("Cannot save an unfitted model.")

        state = {
            "version": "1.0.0",
            "model_type": "HybridQuantumClassifier",
            "disclaimer": (
                "EXPERIMENTAL RESEARCH MODEL. NO CLAIM OF QUANTUM ADVANTAGE. "
                "FOR IN-SILICO INVESTIGATION ONLY."
            ),
            "architecture": asdict(self.config),
            "optimizer_name": self.optimizer_name,
            "maxiter": self.maxiter,
            "weights": self.weights_.tolist(),
            "training_history": self.training_history_,
            "normalizer": self.normalizer.to_dict(),
        }

        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(state, f, indent=2)

        logger.info(f"Saved QNN model state to {filepath}")
        return filepath

    @classmethod
    def load(cls, filepath: str) -> "HybridQuantumClassifier":
        """
        Restores a trained HybridQuantumClassifier from a saved JSON file.
        """
        if not os.path.exists(filepath):
            raise FileNotFoundError(f"Model file not found: {filepath}")

        with open(filepath, "r", encoding="utf-8") as f:
            state = json.load(f)

        arch = state["architecture"]
        instance = cls(
            num_qubits=arch["num_qubits"],
            feature_map_type=arch["feature_map_type"],
            ansatz_type=arch["ansatz_type"],
            feature_reps=arch["feature_reps"],
            ansatz_reps=arch["ansatz_reps"],
            entanglement=arch["entanglement"],
            optimizer_name=state.get("optimizer_name", "COBYLA"),
            maxiter=state.get("maxiter", 50),
        )

        instance.weights_ = np.array(state["weights"], dtype=np.float64)
        instance.is_fitted_ = True
        instance.training_history_ = state.get("training_history", [])
        if "normalizer" in state:
            instance.normalizer = QuantumFeatureNormalizer.from_dict(state["normalizer"])

        logger.info(f"Loaded QNN model successfully from {filepath}")
        return instance

    def summary(self) -> Dict[str, Any]:
        """Returns a structural summary of the quantum circuit and model state."""
        return {
            "num_qubits": self.config.num_qubits,
            "circuit_depth": self.circuit.depth(),
            "num_circuit_operations": len(self.circuit.data),
            "feature_map_parameters": len(self.feature_params),
            "ansatz_trainable_parameters": self.num_weights,
            "total_circuit_parameters": len(self.circuit_params),
            "optimizer": self.optimizer_name,
            "is_fitted": self.is_fitted_,
            "final_training_loss": (
                self.training_history_[-1] if self.training_history_ else None
            ),
        }


