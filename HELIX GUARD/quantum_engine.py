def generate_synthetic_genetic_data(
    n_samples: int = 120,
    n_features: int = 4,
    noise: float = 0.05,
    seed: int = 42,
) -> Tuple[np.ndarray, np.ndarray, List[str]]:
    """
    Generates clearly labelled synthetic demonstration data representing
    compact variant risk factors for algorithmic validation.

    SCIENTIFIC NOTE:
    This dataset is synthetic and artificially generated for computational testing.
    It does NOT represent clinical genomic findings or medical diagnoses.

    Synthetic features modeled:
    1. simulated_allele_frequency: Rare in pathogenic (e.g., < 0.01), common in benign
    2. simulated_conservation_score: High conservation indicates structural intolerance
    3. simulated_gc_content: Local nucleotide composition ratio
    4. simulated_molecular_impact: Severity of amino acid / substitution shift

    Returns:
        X: Feature array of shape (n_samples, 4)
        y: Binary ground-truth labels (0 = Benign/Neutral, 1 = Pathogenic-like)
        feature_names: List of feature descriptions
    """
    rng = np.random.RandomState(seed)

    feature_names = [
        "simulated_allele_frequency",
        "simulated_conservation_score",
        "simulated_gc_content",
        "simulated_molecular_impact",
    ]

    # Generate half benign, half pathogenic-like synthetic variants
    n_half = n_samples // 2

    # Class 0: Synthetic Benign / Common variants
    # Higher allele frequency, lower conservation, lower molecular impact
    af_benign = rng.uniform(0.05, 0.50, size=n_half)
    cons_benign = rng.beta(2, 5, size=n_half)          # skewed toward lower conservation
    gc_benign = rng.normal(0.45, 0.08, size=n_half)    # typical human GC content
    impact_benign = rng.uniform(0.0, 0.4, size=n_half)

    X_benign = np.column_stack([af_benign, cons_benign, gc_benign, impact_benign])
    y_benign = np.zeros(n_half, dtype=int)

    # Class 1: Synthetic Pathogenic / Deleterious variants
    # Very rare allele frequency, high conservation, high molecular disruption
    af_patho = rng.exponential(scale=0.005, size=n_half)
    af_patho = np.clip(af_patho, 0.0001, 0.02)
    cons_patho = rng.beta(5, 2, size=n_half)           # skewed toward high conservation
    gc_patho = rng.normal(0.58, 0.10, size=n_half)     # slightly elevated / CpG island
    impact_patho = rng.uniform(0.6, 1.0, size=n_half)

    X_patho = np.column_stack([af_patho, cons_patho, gc_patho, impact_patho])
    y_patho = np.ones(n_half, dtype=int)

    # Concatenate and apply slight realistic noise
    X = np.vstack([X_benign, X_patho])
    y = np.concatenate([y_benign, y_patho])

    if noise > 0.0:
        X += rng.normal(0.0, noise, size=X.shape)
        X = np.clip(X, 0.0, None)

    # Shuffle dataset
    shuffle_idx = rng.permutation(len(X))
    X = X[shuffle_idx]
    y = y[shuffle_idx]

    return X, y, feature_names


